import json
import time
import urllib.error
import urllib.request
from typing import Any

from mcp.server import MCPServer

mcp = MCPServer("UGAFStudio OpenCode")

OPENCODE_URL = "http://127.0.0.1:4096"


def request_json(
    method: str,
    url: str,
    body: dict[str, Any] | None = None,
) -> tuple[int, dict[str, Any] | list[Any] | None]:
    data = None

    headers = {
        "Accept": "application/json",
    }

    if body is not None:
        data = json.dumps(
            body,
            ensure_ascii=False,
        ).encode("utf-8")

        headers["Content-Type"] = "application/json; charset=utf-8"

    request = urllib.request.Request(
        url,
        data=data,
        headers=headers,
        method=method,
    )

    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            status = response.status
            raw = response.read().decode("utf-8")

            if not raw:
                return status, None

            return status, json.loads(raw)

    except urllib.error.HTTPError as exc:
        error_body = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"OpenCode HTTP {exc.code}: {error_body}") from exc


def get_messages(session_id: str) -> list[dict[str, Any]]:
    _, result = request_json(
        "GET",
        f"{OPENCODE_URL}/session/{session_id}/message",
    )

    if not isinstance(result, list):
        return []

    return result


def extract_text(message: dict[str, Any]) -> str:
    texts = []

    for part in message.get("parts", []):
        if part.get("type") == "text":
            text = part.get("text")
            if text:
                texts.append(text)

    return "\n".join(texts)


@mcp.tool()
def ping() -> str:
    """Check that the UGAFStudio OpenCode MCP server is alive."""
    return "UGAF_MCP_OK"


@mcp.tool()
def opencode_health() -> str:
    """Check the health and version of the local OpenCode server."""
    _, result = request_json(
        "GET",
        f"{OPENCODE_URL}/global/health",
    )

    if not isinstance(result, dict):
        raise RuntimeError("Invalid OpenCode health response")

    return json.dumps(
        {
            "healthy": result.get("healthy"),
            "version": result.get("version"),
        },
        ensure_ascii=False,
    )


@mcp.tool()
def opencode_send(
    prompt: str,
    session_id: str | None = None,
    new_session: bool = False,
    title: str = "UGAFStudio MCP Session",
    timeout_sec: int = 300,
) -> str:
    """
    Send a task to the local OpenCode Build Agent and wait for completion.

    Uses OpenCode's asynchronous prompt endpoint and polls the session
    messages until the new assistant response is completed.
    """

    if not session_id or new_session:
        _, session = request_json(
            "POST",
            f"{OPENCODE_URL}/session",
            {
                "title": title,
            },
        )

        if not isinstance(session, dict) or not session.get("id"):
            raise RuntimeError("OpenCode did not return a session ID")

        session_id = session["id"]

    # Capture existing messages so we can identify the response
    # generated by this request.
    before_messages = get_messages(session_id)

    before_ids = {message.get("info", {}).get("id") for message in before_messages}

    # OpenCode API documents this endpoint as asynchronous and returning 204.
    status, _ = request_json(
        "POST",
        f"{OPENCODE_URL}/session/{session_id}/prompt_async",
        {
            "parts": [
                {
                    "type": "text",
                    "text": prompt,
                }
            ]
        },
    )

    if status != 204:
        raise RuntimeError(f"OpenCode async prompt returned unexpected HTTP {status}")

    deadline = time.monotonic() + timeout_sec

    while time.monotonic() < deadline:
        messages = get_messages(session_id)

        # Search newest messages first.
        for message in reversed(messages):
            info = message.get("info", {})
            message_id = info.get("id")

            if message_id in before_ids:
                continue

            if info.get("role") != "assistant":
                continue

            # OpenCode's message model contains completed timing
            # information when generation has finished.
            message_time = info.get("time", {})

            if not message_time.get("completed"):
                continue

            response_text = extract_text(message)

            return json.dumps(
                {
                    "session_id": session_id,
                    "message_id": message_id,
                    "model": info.get("modelID"),
                    "provider": info.get("providerID"),
                    "agent": info.get("agent"),
                    "mode": info.get("mode"),
                    "finish": info.get("finish"),
                    "response": response_text,
                },
                ensure_ascii=False,
            )

        time.sleep(1)

    raise TimeoutError(f"OpenCode did not complete the request within {timeout_sec} seconds")


if __name__ == "__main__":
    mcp.run()
